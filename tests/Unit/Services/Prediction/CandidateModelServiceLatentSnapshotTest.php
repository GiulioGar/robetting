<?php

namespace Tests\Unit\Services\Prediction;

use App\Services\Prediction\CandidateModelService;
use App\Services\Prediction\PredictionEngineV1;
use PHPUnit\Framework\TestCase;

/**
 * P12B — Candidate44 BP latent snapshot integration tests.
 *
 * Isolated temp artifact dir per test (copies the real candidate44_bp
 * artifact + a controlled latent_strength_current.json fixture) so the
 * anti-leakage timing scenarios are fully deterministic.
 */
class CandidateModelServiceLatentSnapshotTest extends TestCase
{
    private const MODELS_DIR = __DIR__ . '/../../../../tools/models';
    private const GOLDEN_PATH = __DIR__ . '/../../../Fixtures/Prediction/prediction_engine_v1_golden.json';

    private string $tempDir;
    private array $sampleFeatures;
    private string $sampleKickoff;

    protected function setUp(): void
    {
        parent::setUp();

        $golden = json_decode(file_get_contents(self::GOLDEN_PATH), true, 512, JSON_THROW_ON_ERROR);
        $case   = $golden['cases'][0];
        $this->sampleFeatures = $case['features'];
        $this->sampleKickoff  = $case['kickoff_at'];

        $v1Path = realpath(self::MODELS_DIR . '/prediction_engine_v1.json') ?: self::MODELS_DIR . '/prediction_engine_v1.json';
        PredictionEngineV1::setArtifactPath($v1Path);

        $this->tempDir = sys_get_temp_dir() . '/c44_snapshot_test_' . uniqid();
        mkdir($this->tempDir);

        // Real Candidate44 BP artifact (generated by generate_candidate44_bp_artifact.py).
        copy(
            realpath(self::MODELS_DIR) . '/prediction_engine_candidate44_bp.json',
            $this->tempDir . '/prediction_engine_candidate44_bp.json',
        );

        CandidateModelService::setArtifactDir($this->tempDir);
    }

    protected function tearDown(): void
    {
        CandidateModelService::reset();
        PredictionEngineV1::reset();
        array_map('unlink', glob($this->tempDir . '/*'));
        rmdir($this->tempDir);
        parent::tearDown();
    }

    private function writeSnapshot(string $generatedAt, array $teams): void
    {
        file_put_contents(
            $this->tempDir . '/latent_strength_current.json',
            json_encode([
                'generated_at'            => $generatedAt,
                'last_match_included_at'  => '2026-01-01T00:00:00Z',
                'model_version'           => 'test',
                'matches_used'            => 100,
                'teams'                   => $teams,
            ])
        );
    }

    // ─────────────────────────────────────────────────────────────────────────

    /** @test */
    public function test_snapshot_loader_and_44_features_produce_valid_result(): void
    {
        // Kickoff is in the golden case (a real historical/known date); use a snapshot
        // generated well before it so the anti-leakage check passes.
        $before = date('Y-m-d\TH:i:s\Z', strtotime($this->sampleKickoff) - 3600 * 24 * 365);
        $this->writeSnapshot($before, [
            ['team_id' => 111, 'attack' => 0.30, 'defence' => -0.20],
            ['team_id' => 222, 'attack' => -0.10, 'defence' => 0.15],
        ]);

        $service = new CandidateModelService();
        $result  = $service->compare($this->sampleFeatures, 111, 222, $this->sampleKickoff);

        $this->assertTrue($result['candidate44_bp_available']);
        $this->assertNotNull($result['candidate44_bp']);
        $this->assertArrayHasKey('lambda_home', $result['candidate44_bp']);
        $this->assertArrayHasKey('lambda_away', $result['candidate44_bp']);
        $this->assertArrayHasKey('lambda3', $result['candidate44_bp']);
        $this->assertEqualsWithDelta(0.15, $result['candidate44_bp']['lambda3'], 1e-9);

        // 44 features declared in the artifact actually consumed by the pipeline.
        $artifact = json_decode(
            file_get_contents($this->tempDir . '/prediction_engine_candidate44_bp.json'),
            true
        );
        $this->assertCount(44, $artifact['features']);
        $this->assertContains('latent_attack_home', $artifact['features']);
        $this->assertContains('latent_defence_home', $artifact['features']);
        $this->assertContains('latent_attack_away', $artifact['features']);
        $this->assertContains('latent_defence_away', $artifact['features']);
    }

    /** @test */
    public function test_probabilities_sum_to_one(): void
    {
        $before = date('Y-m-d\TH:i:s\Z', strtotime($this->sampleKickoff) - 3600 * 24 * 365);
        $this->writeSnapshot($before, [
            ['team_id' => 111, 'attack' => 0.30, 'defence' => -0.20],
            ['team_id' => 222, 'attack' => -0.10, 'defence' => 0.15],
        ]);

        $service = new CandidateModelService();
        $result  = $service->compare($this->sampleFeatures, 111, 222, $this->sampleKickoff);

        $this->assertTrue($result['candidate44_bp_available']);
        $sum = $result['candidate44_bp']['probability_home']
             + $result['candidate44_bp']['probability_draw']
             + $result['candidate44_bp']['probability_away'];
        $this->assertEqualsWithDelta(1.0, $sum, 1e-8);
    }

    /**
     * @test
     * Anti-leakage: snapshot generated AFTER (or at) kickoff must never be used.
     */
    public function test_anti_leakage_historical_match_is_unavailable(): void
    {
        // Snapshot generated well AFTER the match kickoff — must be rejected.
        $after = date('Y-m-d\TH:i:s\Z', strtotime($this->sampleKickoff) + 3600 * 24 * 30);
        $this->writeSnapshot($after, [
            ['team_id' => 111, 'attack' => 0.30, 'defence' => -0.20],
            ['team_id' => 222, 'attack' => -0.10, 'defence' => 0.15],
        ]);

        $service = new CandidateModelService();
        $result  = $service->compare($this->sampleFeatures, 111, 222, $this->sampleKickoff);

        $this->assertFalse($result['candidate44_bp_available']);
        $this->assertNull($result['candidate44_bp']);
    }

    /**
     * @test
     * Snapshot generated_at exactly equal to kickoff must also be rejected
     * (strict "<" required, not "<=").
     */
    public function test_anti_leakage_equal_timestamp_is_unavailable(): void
    {
        $this->writeSnapshot($this->sampleKickoff, [
            ['team_id' => 111, 'attack' => 0.30, 'defence' => -0.20],
            ['team_id' => 222, 'attack' => -0.10, 'defence' => 0.15],
        ]);

        $service = new CandidateModelService();
        $result  = $service->compare($this->sampleFeatures, 111, 222, $this->sampleKickoff);

        $this->assertFalse($result['candidate44_bp_available']);
    }

    /** @test */
    public function test_future_match_with_valid_snapshot_is_available(): void
    {
        $futureKickoff = date('Y-m-d\TH:i:s\Z', strtotime('+30 days'));
        $now = date('Y-m-d\TH:i:s\Z');
        $this->writeSnapshot($now, [
            ['team_id' => 111, 'attack' => 0.30, 'defence' => -0.20],
            ['team_id' => 222, 'attack' => -0.10, 'defence' => 0.15],
        ]);

        $service = new CandidateModelService();
        $result  = $service->compare($this->sampleFeatures, 111, 222, $futureKickoff);

        $this->assertTrue($result['candidate44_bp_available']);
        $this->assertNotNull($result['candidate44_bp']);
    }

    /** @test */
    public function test_missing_team_in_snapshot_is_unavailable(): void
    {
        $before = date('Y-m-d\TH:i:s\Z', strtotime($this->sampleKickoff) - 3600 * 24 * 365);
        $this->writeSnapshot($before, [
            ['team_id' => 111, 'attack' => 0.30, 'defence' => -0.20],
            // team 222 intentionally absent
        ]);

        $service = new CandidateModelService();
        $result  = $service->compare($this->sampleFeatures, 111, 222, $this->sampleKickoff);

        $this->assertFalse($result['candidate44_bp_available']);
        $this->assertNull($result['candidate44_bp']);
    }

    /** @test */
    public function test_missing_snapshot_file_is_unavailable_not_fatal(): void
    {
        // No writeSnapshot() call at all — file does not exist.
        $service = new CandidateModelService();
        $result  = $service->compare($this->sampleFeatures, 111, 222, $this->sampleKickoff);

        $this->assertFalse($result['candidate44_bp_available']);
        $this->assertNull($result['candidate44_bp']);
        // full59 must still be computed — a missing optional artifact is never fatal.
        $this->assertArrayHasKey('lambda_home', $result['full59']);
    }

    /**
     * @test
     * FULL59 and Candidate40 must be byte-identical whether or not the
     * Candidate44 team/kickoff arguments are supplied.
     */
    public function test_full59_and_candidate40_unchanged_by_new_arguments(): void
    {
        // Candidate40 artifact needed for this comparison.
        copy(
            realpath(self::MODELS_DIR) . '/prediction_engine_candidate40.json',
            $this->tempDir . '/prediction_engine_candidate40.json',
        );

        $before = date('Y-m-d\TH:i:s\Z', strtotime($this->sampleKickoff) - 3600 * 24 * 365);
        $this->writeSnapshot($before, [
            ['team_id' => 111, 'attack' => 0.30, 'defence' => -0.20],
            ['team_id' => 222, 'attack' => -0.10, 'defence' => 0.15],
        ]);

        $service = new CandidateModelService();

        $withoutLatentArgs = $service->compare($this->sampleFeatures);
        $withLatentArgs    = $service->compare($this->sampleFeatures, 111, 222, $this->sampleKickoff);

        $this->assertSame($withoutLatentArgs['full59'], $withLatentArgs['full59']);
        $this->assertSame($withoutLatentArgs['candidate40'], $withLatentArgs['candidate40']);

        // Only the new call attempted (and succeeded at) Candidate44.
        $this->assertFalse($withoutLatentArgs['candidate44_bp_available']);
        $this->assertTrue($withLatentArgs['candidate44_bp_available']);
    }
}
